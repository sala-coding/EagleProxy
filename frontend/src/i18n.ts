const dicts: Record<Lang, Record<string, string>> = {zh, en, ru};

let current: Lang = 'zh';

// SetLang switches the active language.
export function setLang(l: Lang) {
    current = dicts[l] ? l : 'zh';
}

// Lang returns the active language.
export function getLang(): Lang {
    return current;
}

// T translates a key, falling back to Chinese then the key itself, and fills
// {0}, {1}… with args in order — the same substitution the tips table gets,
// because a few strings here are parameterised the same way.
export function t(key: string, ...args: (string | number)[]): string {
    const s = dicts[current][key] ?? zh[key] ?? key;
    if (!args.length) return s;
    return s.replace(/\{(\d+)\}/g, (m, i) => {
        const v = args[Number(i)];
        return v === undefined ? m : String(v);
    });
}

// LangFromCode maps the language setting to a language. 0–4 are nekoray's own numbers
// (0 Chinese, 1 English, 2 traditional Chinese, 3 Persian, 4 Russian); 2 and 3 are not
// shipped here, so a file that carries either falls back to Chinese — 3 used to be
// Persian, which is no longer offered, and an old file that carries it now lands on
// Chinese the way 2 always did.
export function langFromCode(code: number): Lang {
    switch (code) {
        case 1:
            return 'en';
        case 4:
            return 'ru';
        default:
            return 'zh';
    }
}

// CodeOfLang is langFromCode read the other way: the number the settings file
// holds for a language. The machine's own answer arrives as a language (see
// SystemLang) and the window wears languages, not numbers — but the settings form
// and the file both speak numbers, so the detection has to be handed one.
export function codeOfLang(lang: Lang): number {
    switch (lang) {
        case 'en':
            return 1;
        case 'ru':
            return 4;
        default:
            return 0;
    }
}

// The languages shipped as a file each (see ./i18n/), in the order the settings
// form lists them. One list rather than a repetition per language: it is what says
// which codes are ours, and a language added as a file but missed here would be a
// language the window can wear but never offer.
const ALL: Lang[] = ['zh', 'en', 'ru'];

// SystemLang is the language the machine is speaking, as the web view reports it.
// The web view takes its locale from the system on every desktop this app runs on,
// which is the same answer the reader's other programs are giving — a window that
// spoke a different language from the one it was opened in would be the app's own
// decision to make, and this is where that decision is made.
//
// The tag carries a region as well as a language ("zh-CN", "en-GB"), and the region
// is dropped: the dictionaries are one per language, not one per place, so "en-GB"
// and "en-US" are the same file and either may be answered for with "en".
//
// A language with no dictionary behind it is none of ours — a French or Japanese
// machine lands here — and Chinese is what this app answers in that case: it is
// the one language every dictionary can fall back on (see t) and the one the file's
// own zero value already means (see langFromCode), so "no match" and "Chinese" are
// the same answer rather than two different ones.
export function systemLang(): Lang {
    const nav: (Navigator & {userLanguage?: string}) | undefined =
        typeof navigator === 'undefined' ? undefined : navigator;
    const raw = nav?.languages?.[0] || nav?.language || nav?.userLanguage || '';
    const code = raw.toLowerCase().split(/[-_]/)[0];
    return (ALL as string[]).includes(code) ? (code as Lang) : 'zh';
}
