// Generates src/lib/icons.ts: one Vue functional component per MingCute icon
// this app uses, with the SVG body inlined from @iconify-json/mingcute. The
// export names match the old @mingcute/react exports (AddFilled, CloseFilled,
// ...) so migrations are a one-line import change per file.
//
// Usage: npm run gen:icons   (requires devDependencies installed)
import {readFileSync, writeFileSync} from 'node:fs';
import {dirname, join} from 'node:path';
import {fileURLToPath} from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const db = JSON.parse(readFileSync(join(here, '../node_modules/@iconify-json/mingcute/icons.json'), 'utf8'));

// The names the app imports, and the Iconify "mingcute:" name each maps to.
// Fill the alias table here whenever a lookup below cannot find a name.
const aliases = {
    AddFilled: 'add-fill',
    ArrowRightFilled: 'arrow-right-fill',
    BookmarksFilled: 'bookmarks-fill',
    Layout4Filled: 'layout-4-fill',
    LayoutBottomCloseFilled: 'layout-bottom-close-fill',
    CheckCircleFilled: 'check-circle-fill',
    CheckFilled: 'check-fill',
    ClockFilled: 'clock-fill',
    CloseCircleFilled: 'close-circle-fill',
    CloseFilled: 'close-fill',
    CloudFilled: 'cloud-fill',
    CodeFilled: 'code-fill',
    CopyFilled: 'copy-2-fill',
    DashboardFilled: 'dashboard-fill',
    Delete2Filled: 'delete-2-fill',
    Delete3Filled: 'delete-3-fill',
    Download3Filled: 'download-3-fill',
    EarthFilled: 'earth-fill',
    Edit2Filled: 'edit-2-fill',
    EraserFilled: 'eraser-fill',
    FileExportFilled: 'file-export-fill',
    FileImportFilled: 'file-import-fill',
    FlashFilled: 'flash-fill',
    FolderFilled: 'folder-fill',
    FolderOpenFilled: 'folder-open-fill',
    ForbidCircleFilled: 'forbid-circle-fill',
    InformationFilled: 'information-fill',
    LayersFilled: 'layers-fill',
    Link2Filled: 'link-2-fill',
    Link3Filled: 'link-3-fill',
    LoadingFilled: 'loading-fill',
    PlayFilled: 'play-fill',
    PauseFilled: 'pause-fill',
    PluginFilled: 'plugin-fill',
    QrcodeFilled: 'qrcode-fill',
    QuestionFilled: 'question-fill',
    Refresh1Filled: 'refresh-1-fill',
    RightFilled: 'right-fill',
    SaveFilled: 'save-fill',
    ServerFilled: 'server-fill',
    ShieldFilled: 'shield-fill',
    ShuffleFilled: 'shuffle-fill',
    SparklesFilled: 'sparkles-fill',
    StopFilled: 'stop-fill',
    TerminalBoxFilled: 'terminal-box-fill',
    ThumbUpFilled: 'thumb-up-fill',
    TransferHorizontalFilled: 'transfer-horizontal-fill',
};

const norm = (s) => s.toLowerCase().replace(/[^a-z0-9]/g, '');
const byNorm = new Map(Object.keys(db.icons).map((n) => [norm(n), n]));

const missing = [];
const resolved = {};
for (const [exportName, wanted] of Object.entries(aliases)) {
    let name = db.icons[wanted] ? wanted : byNorm.get(norm(wanted));
    if (!name) missing.push(`${exportName} -> ${wanted}`);
    else resolved[exportName] = name;
}
if (missing.length) {
    console.error('Unresolved icons (fix the alias table in scripts/gen-icons.mjs):');
    for (const m of missing) console.error('  ' + m);
    process.exit(1);
}

const lines = [
    '// Generated by scripts/gen-icons.mjs — do not edit by hand. Re-run `npm run gen:icons`',
    '// after changing the alias table there. One Vue functional component per MingCute',
    '// icon, SVG body inlined; renders at 1em and takes the current text colour, so',
    '// <AddFilled className="ic"/> keeps working exactly as it did under React.',
    "import {defineComponent, h, type DefineComponent} from 'vue';",
    '',
    'const mk = (name: string, body: string) => defineComponent({',
    '    name,',
    '    inheritAttrs: false,',
    '    setup(_, {attrs}) {',
    "        return () => h('svg', {viewBox: '0 0 24 24', width: '1em', height: '1em', fill: 'currentColor', ...attrs, innerHTML: body});",
    '    },',
    '}) as DefineComponent<{className?: string}>;',
    '',
];

for (const [exportName, name] of Object.entries(resolved)) {
    const icon = db.icons[name];
    if (!icon.body) {
        console.error(`Icon "${name}" has no body in the icon set`);
        process.exit(1);
    }
    lines.push(`export const ${exportName} = mk('${name}', ${JSON.stringify(icon.body)});`);
    lines.push('');
}

const out = join(here, '../src/lib/icons.ts');
writeFileSync(out, lines.join('\n'));
console.log(`Wrote ${Object.keys(resolved).length} icons to src/lib/icons.ts`);
